#!/bin/bash
# Copy CUDA, TensorRT, OpenCV and ONNX Runtime headers into .sysroot/ (git-ignored),
# so host VS Code IntelliSense sees exactly the versions the container compiles against.
# Runs on VS Code folder open; only refreshes when the SDK image changes.
set -euo pipefail
PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
IMAGE="${SEMVECNET_IMAGE:-semvecnet:dev-ort}"
OPENCV_IMAGE="${SEMVECNET_OPENCV_IMAGE:-$IMAGE}"
SYSROOT="$PROJECT_DIR/.sysroot"

mkdir -p "$SYSROOT"
exec 9>"$SYSROOT/.sync.lock"
flock 9

"$PROJECT_DIR/tool/docker_run.sh" --prepare-image
image_id=$(docker image inspect --format '{{.Id}}' "$IMAGE")
opencv_id=$(docker image inspect --format '{{.Id}}' "$OPENCV_IMAGE")
script_hash=$(sha256sum "$0")
stamp="$image_id $opencv_id ${script_hash%% *} $PROJECT_DIR"
if [ -f "$SYSROOT/.stamp" ] && [ "$(<"$SYSROOT/.stamp")" = "$stamp" ] &&
   [ -f "$SYSROOT/cuda/include/cuda_runtime.h" ] &&
   [ -f "$SYSROOT/tensorrt/include/NvInfer.h" ] &&
   [ -f "$SYSROOT/opencv/include/opencv2/core.hpp" ] &&
   [ -f "$SYSROOT/onnxruntime/include/onnxruntime_cxx_api.h" ] &&
   [ -f "$PROJECT_DIR/.clangd" ]; then
  exit 0
fi

if ! docker run --rm --entrypoint test "$OPENCV_IMAGE" -f /usr/include/opencv4/opencv2/core.hpp; then
  echo "OpenCV development headers not found in $OPENCV_IMAGE." >&2
  echo "Rebuild the dev image with libopencv-dev, or set SEMVECNET_OPENCV_IMAGE to a local image that has it." >&2
  exit 1
fi
if ! docker run --rm --entrypoint sh "$IMAGE" -c 'test -n "$ONNXRUNTIME_ROOT" && test -f "$ONNXRUNTIME_ROOT/include/onnxruntime_cxx_api.h"'; then
  echo "ONNX Runtime development headers not found in $IMAGE. Rebuild the dev image." >&2
  exit 1
fi

staging=$(mktemp -d "$SYSROOT/.sync.XXXXXX")
trap 'rm -rf -- "$staging"' EXIT
# bin/ is empty, but clang/clangd need it to recognise .sysroot/cuda as a CUDA install.
mkdir -p "$staging/cuda/bin" "$staging/tensorrt/include" "$staging/opencv/include" "$staging/onnxruntime" "$staging/previous"

# --entrypoint bypasses NVIDIA's entrypoint, which prints a banner to stdout and corrupts the tar stream.
# /usr/local/cuda/include is a symlink chain; -h dereferences it.
docker run --rm --entrypoint tar "$IMAGE" -C /usr/local/cuda -chf - include \
  | tar -C "$staging/cuda" -xf -
docker run --rm --entrypoint sh "$IMAGE" -c 'cd /usr/include/x86_64-linux-gnu && tar -chf - Nv*.h' \
  | tar -C "$staging/tensorrt/include" -xf -
docker run --rm --entrypoint tar "$OPENCV_IMAGE" -C /usr/include/opencv4 -chf - opencv2 \
  | tar -C "$staging/opencv/include" -xf -
docker run --rm --entrypoint sh "$IMAGE" -c 'tar -C "$ONNXRUNTIME_ROOT" -chf - include' \
  | tar -C "$staging/onnxruntime" -xf -

# clangd: build/compile_commands.json comes from the container, so add the host copies of the
# headers on top of it (and on top of clangd's fallback flags before the first build).
cat > "$staging/clangd" <<CLANGD
# Generated by tool/sync_headers.sh (git-ignored). Absolute paths, so it works for every file.
CompileFlags:
  Add:
    - -I$PROJECT_DIR/include
    - -I$PROJECT_DIR/src
    - -isystem$SYSROOT/tensorrt/include
    - -isystem$SYSROOT/cuda/include
    - -isystem$SYSROOT/opencv/include
    - -isystem$SYSROOT/onnxruntime/include
    - --cuda-path=$SYSROOT/cuda
    - --cuda-host-only
    - -nocudalib
    - --no-cuda-version-check
    - -Wno-unknown-cuda-version
    - -Wno-unused-command-line-argument
    - -std=c++17
CLANGD

for sdk in cuda tensorrt opencv onnxruntime; do
  if [ -e "$SYSROOT/$sdk" ]; then
    mv -- "$SYSROOT/$sdk" "$staging/previous/"
  fi
  mv -- "$staging/$sdk" "$SYSROOT/"
done
mv -- "$staging/clangd" "$PROJECT_DIR/.clangd"
printf '%s\n' "$stamp" > "$SYSROOT/.stamp"
echo "Headers synced to $SYSROOT"
